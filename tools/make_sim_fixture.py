"""Generate a synthetic, PIN-disabled SIM filesystem for local phone UI tests."""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
# FID, record length (0=transparent), body. No subscriber key or RF service.
files=[
 (0x2fe2,0,bytes.fromhex('98941000000000000041')),
 (0x2f05,0,b'en'+b'\xff'*4),
 (0x6f05,0,b'\x01\xff\xff\xff'),
 (0x6f07,0,bytes.fromhex('080910103254769810')),
 (0x6f20,0,b'\xff'*8+b'\x07'),
 (0x6f30,0,b'\xff'*48),
 # Advertise only implemented services: CHV1 disable, ADN, SMS, PLMN selector,
 # MSISDN, SMS parameters and SPN. Do not advertise SIM Toolkit/FDN/AoC files.
 (0x6f38,0,bytes.fromhex('cf30c30003000000000000000000')),
 (0x6f46,0,b'\x00FPGA SIM'+b'\xff'*8),
 (0x6f7b,0,b'\xff'*12),
 (0x6f7e,0,bytes.fromhex('ffffffff00f110fffe0001')),
 (0x6fad,0,bytes.fromhex('00ffff02')),
 (0x6fae,0,b'\x02'),
 (0x6f78,0,b'\x00\x01'),
 (0x6f74,0,b'\xff'*16),
 (0x6fb7,0,bytes.fromhex('11f2ffffffffff')),
 (0x6f31,0,b'\x05'),
 (0x6f3a,32,b'\xff'*1600),
 # GSM 11.11: a free SMS record has status 00, not reserved status FF.
 (0x6f3c,176,(b'\x00'+b'\xff'*175)*10),
 (0x6f42,46,b'\xff'*46),
 (0x6f43,0,b'\x01\xff'),
 (0x6f40,38,b'\xff'*114),
]
image=bytearray(b'\xff'*4096)
functions=[]
offset=0
entries=[]
for fid,rec,body in files:
    assert offset+len(body)<=len(image)
    image[offset:offset+len(body)]=body
    entries.append((fid,offset,len(body),rec))
    offset+=len(body)
for name,column,width,default in [('ef_base',1,12,0),('ef_size',2,12,0),('ef_record',3,8,0)]:
    functions.append(f'function automatic [{width-1}:0] {name}(input [15:0] fid);\n    case(fid)')
    functions.extend(f"        16'h{row[0]:04x}: {name}={width}'d{row[column]};" for row in entries)
    functions.append(f"        default: {name}={width}'d{default};\n    endcase\nendfunction")
(ROOT/'rtl/nokia/sim_fixture.svh').write_text('// Generated by tools/make_sim_fixture.py\n'+'\n'.join(functions)+'\n')
(ROOT/'rtl/nokia/sim_fixture.hex').write_text('\n'.join(f'{b:02x}' for b in image)+'\n')
print(f'Synthetic SIM fixture: {len(entries)} files, {offset} bytes, 4096-byte RAM image')
